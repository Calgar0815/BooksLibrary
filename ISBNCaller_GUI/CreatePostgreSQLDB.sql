-- FUNCTION: public.getalldates(integer, integer)

-- DROP FUNCTION IF EXISTS public.getalldates(integer, integer);

CREATE OR REPLACE FUNCTION public.getalldates(
	first integer,
	last integer)
    RETURNS TABLE(returnbookid integer) 
    LANGUAGE 'plpgsql'
    COST 100
    VOLATILE PARALLEL UNSAFE
    ROWS 1000

AS $BODY$
BEGIN
    RETURN QUERY
    SELECT BookID FROM Books WHERE RIGHT(PublishingDate, 4)::INT BETWEEN first AND last;
END
$BODY$;

ALTER FUNCTION public.getalldates(integer, integer)
    OWNER TO postgres;
