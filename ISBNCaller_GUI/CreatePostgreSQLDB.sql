-- Table: public.settings

-- DROP TABLE IF EXISTS public.settings;

CREATE TABLE IF NOT EXISTS public.settings
(
    id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    topic character varying NOT NULL,
    setting character varying NOT NULL,
    inuse boolean,
    CONSTRAINT settings_pkey PRIMARY KEY (id)
)

TABLESPACE pg_default;

ALTER TABLE IF EXISTS public.settings
    OWNER to postgres;
-- Index: topicinuse

-- DROP INDEX IF EXISTS public.topicinuse;

CREATE UNIQUE INDEX IF NOT EXISTS topicinuse
    ON public.settings USING btree
    (topic COLLATE pg_catalog."default" ASC NULLS LAST, inuse ASC NULLS LAST)
    WITH (fillfactor=100, deduplicate_items=True)
    TABLESPACE pg_default;
-- Index: topicsetting

-- DROP INDEX IF EXISTS public.topicsetting;

CREATE UNIQUE INDEX IF NOT EXISTS topicsetting
    ON public.settings USING btree
    (topic COLLATE pg_catalog."default" ASC NULLS LAST, setting COLLATE pg_catalog."default" ASC NULLS LAST)
    WITH (fillfactor=100, deduplicate_items=True)
    TABLESPACE pg_default;

