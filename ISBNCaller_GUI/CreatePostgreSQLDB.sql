-- Database: BooksDB

-- DROP DATABASE IF EXISTS "BooksDB";

CREATE DATABASE "BooksDB"
    WITH
    OWNER = postgres
    ENCODING = 'UTF8'
    LC_COLLATE = 'German_Germany.1252'
    LC_CTYPE = 'German_Germany.1252'
    LOCALE_PROVIDER = 'libc'
    TABLESPACE = pg_default
    CONNECTION LIMIT = -1
    IS_TEMPLATE = False;

-- Table: public.authors

-- DROP TABLE IF EXISTS public.authors;

CREATE TABLE IF NOT EXISTS public.authors
(
    authorid integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    prename character varying(255),
    name character varying(255) NOT NULL,
    deleted boolean NOT NULL DEFAULT false,
    CONSTRAINT authors_pkey PRIMARY KEY (authorid)
)

TABLESPACE pg_default;

ALTER TABLE IF EXISTS public.authors
    OWNER to postgres;

-- Table: public.books

-- DROP TABLE IF EXISTS public.books;

CREATE TABLE IF NOT EXISTS public.books
(
    bookid integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    title character varying(255) NOT NULL,
    subtitle character varying(255),
    publishingdate character varying(50),
    format character varying(100),
    isbn13 character varying(13),
    isbn10 character varying(10),
    ispartofseries boolean NOT NULL DEFAULT false,
    deleted boolean NOT NULL DEFAULT false,
    CONSTRAINT books_pkey PRIMARY KEY (bookid)
)

TABLESPACE pg_default;

ALTER TABLE IF EXISTS public.books
    OWNER to postgres;

-- Table: public.bookauthor

-- DROP TABLE IF EXISTS public.bookauthor;

CREATE TABLE IF NOT EXISTS public.bookauthor
(
    bookid integer NOT NULL,
    authorid integer NOT NULL,
    CONSTRAINT bookauthor_pkey PRIMARY KEY (bookid, authorid),
    CONSTRAINT bookauthor_authorid_fkey FOREIGN KEY (authorid)
        REFERENCES public.authors (authorid) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,
    CONSTRAINT bookauthor_bookid_fkey FOREIGN KEY (bookid)
        REFERENCES public.books (bookid) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE NO ACTION
)

TABLESPACE pg_default;

ALTER TABLE IF EXISTS public.bookauthor
    OWNER to postgres;

